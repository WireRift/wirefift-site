function outline(text, size, tracking = 0, typeface = font) {
  const run = typeface.layout(text);
  const scale = size / typeface.unitsPerEm;
  let cursor = 0;
  const paths = run.glyphs.map((glyph, i) => {
    const position = run.positions[i];
    const path = {
      d: glyph.path.toSVG(),
      x: +(cursor + position.xOffset * scale).toFixed(3),
      y: +(position.yOffset * scale).toFixed(3),
    };
    cursor += position.xAdvance * scale + tracking;
    return path;
  });
  return { paths, width: +(cursor - tracking).toFixed(3), scale };
}
