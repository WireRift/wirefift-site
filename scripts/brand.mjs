function symbol(cut, compact = false) {
  const rays = compact
    ? shape.rays.filter((_, i) => i === 0 || i === 3 || i === 4)
    : shape.rays;
  const wires = shape.wires
    .map(
      (d) =>
        `<path d="${d}" fill="currentColor" stroke="${cut}" stroke-width="3.2" stroke-linejoin="round" paint-order="stroke"/>`,
    )
    .join("");
  const signals = rays
    .map((p) => {
      const end = rayEnd(p);
      return `<path d="M${p.x} ${p.y} ${p.ex} ${p.ey}" stroke="#F5AD21"/><path d="M${p.x} ${p.y} ${end.x} ${end.y}"/><circle cx="${p.ex}" cy="${p.ey}" r="${p.r}" fill="${end.outer ? "#F5AD21" : cut}" stroke="none"/>`;
    })
    .join("");
  const detail = compact
    ? ""
    : `<path d="${shape.arrow}" stroke-linecap="butt" fill="#F5AD21" stroke="#F5AD21"/>${shape.sparks.map((p) => `<circle cx="${p.cx}" cy="${p.cy}" r="${p.r}" stroke="none"/>`).join("")}`;
  return `<circle cx="64" cy="60" r="44" fill="#F5AD21"/>${wires}<g fill="${cut}" stroke="${cut}" stroke-width="2.2" stroke-linecap="round">${signals}${detail}</g><path d="${shape.bolt}" fill="currentColor" stroke="${cut}" stroke-width="3.8" stroke-linejoin="miter" paint-order="stroke"/>`;
}
